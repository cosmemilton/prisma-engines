// Added for experimental Firebird support (2026-10-18); see MODIFICATIONS.md.
//! Firebird 3 catalog description through a driver adapter.
//!
//! Catalog definitions: <https://www.firebirdsql.org/file/documentation/html/en/refdocs/fblangref30/firebird-30-language-reference.html>.
//! Identity is recognized from RDB$IDENTITY_TYPE, never inferred from trigger text.
//! Reading the catalog does not advance generators or inspect their current values.

use super::*;
use crate::getters::Getter;
use psl::{builtin_connectors::FirebirdType, datamodel_connector::NativeTypeInstance};
use quaint::{
    connector::{Queryable, ResultRow, ResultSet},
    error::{Error, ErrorKind},
};
use std::{
    collections::{BTreeMap, btree_map::Entry},
    str::FromStr,
    sync::LazyLock,
};

/// Internal table used to serialize migrations. It is not an application table.
pub const MIGRATION_LOCK_TABLE: &str = "_prisma_migrate_lock";

/// Connector-specific metadata which cannot be expressed in the shared SQL schema.
#[derive(Debug, Clone, Default)]
pub struct FirebirdSchemaExt {
    /// Identity columns and the names of their internal generators.
    pub identities: Vec<(TableColumnId, Identity)>,
    /// Declared initial values and increments, not live generator counters.
    pub generators: Vec<Generator>,
    /// Physical backing index names, separate from constraint names.
    pub indexes: Vec<(IndexId, IndexMetadata)>,
    /// Physical backing index names for foreign keys.
    pub foreign_key_indexes: Vec<(ForeignKeyId, String)>,
    /// Column domain and character set metadata.
    pub columns: Vec<(TableColumnId, ColumnMetadata)>,
    /// User trigger definitions, retained without inferring generated values.
    pub triggers: Vec<Trigger>,
}

impl FirebirdSchemaExt {
    /// Physical index information for a shared schema index.
    pub fn index_metadata(&self, index: IndexId) -> Option<&IndexMetadata> {
        self.indexes
            .iter()
            .find_map(|(id, metadata)| (*id == index).then_some(metadata))
    }

    /// Identity metadata for a column, if the database declares it as identity.
    pub fn identity(&self, column: TableColumnId) -> Option<&Identity> {
        self.identities
            .iter()
            .find_map(|(id, identity)| (*id == column).then_some(identity))
    }
}

/// A Firebird 3 GENERATED BY DEFAULT identity.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Identity {
    /// Name of the system generator associated with the identity column.
    pub generator_name: String,
}

/// A catalog generator, also called a sequence.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Generator {
    /// Database name, preserving quoted identifier case.
    pub name: String,
    /// Catalog system flag (6 denotes an identity generator).
    pub system_flag: i64,
    /// Declared initial counter value. Firebird 3 generates initial_value + increment first.
    pub initial_value: i64,
    /// Declared increment.
    pub increment: i64,
}

/// The physical index underlying a shared schema index or constraint.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct IndexMetadata {
    /// Physical database index name.
    pub database_name: String,
    /// Constraint name, if this index backs a primary or unique constraint.
    pub constraint_name: Option<String>,
}

/// Extra column attributes retained for migrations and diagnostics.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ColumnMetadata {
    /// RDB$FIELD_SOURCE, including automatically generated domains.
    pub field_source: String,
    /// Character set for textual types.
    pub character_set: Option<String>,
    /// Effective collation identifier.
    pub collation_id: i64,
    /// NOT NULL inherited from the underlying domain.
    pub domain_not_null: bool,
    /// Domain default SQL source, retained separately from column overrides.
    pub domain_default: Option<String>,
    /// Column-level default SQL source.
    pub column_default: Option<String>,
}

/// A user trigger whose semantics are not inferred by introspection.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Trigger {
    /// Database trigger name.
    pub name: String,
    /// Owning table, absent for database or DDL triggers.
    pub relation_name: Option<String>,
    /// Source definition, if retained by the database.
    pub source: Option<String>,
    /// Whether the trigger is inactive.
    pub inactive: bool,
}

/// A Firebird 3 schema describer. The connection is supplied by the external adapter.
pub struct SqlSchemaDescriber<'a> {
    conn: &'a dyn Queryable,
}

impl<'a> SqlSchemaDescriber<'a> {
    /// Construct a describer without opening an additional connection.
    pub fn new(conn: &'a dyn Queryable) -> Self {
        Self { conn }
    }

    /// Describe persistent tables in the current Firebird database.
    pub async fn describe_impl(&self) -> DescriberResult<SqlSchema> {
        let version = self.version().await?;
        if !version.as_deref().is_some_and(|version| version.starts_with("3.")) {
            return Err(unsupported(format!(
                "database version {version:?}; this describer requires Firebird 3.x"
            )));
        }
        let dialect = self
            .conn
            .query_raw("SELECT MON$SQL_DIALECT AS \"dialect\" FROM MON$DATABASE", &[])
            .await?
            .into_single()?;
        let dialect = required_i64(&dialect, "dialect")?;
        if dialect != 3 {
            return Err(unsupported(format!(
                "SQL dialect {dialect}; this describer requires SQL dialect 3 to preserve numeric types"
            )));
        }

        // Keep all queries on the supplied connection. The caller owns transaction boundaries.
        let relations = self.conn.query_raw(RELATIONS, &[]).await?;
        let columns = self.conn.query_raw(COLUMNS, &[]).await?;
        let indexes = self.conn.query_raw(INDEXES, &[]).await?;
        let foreign_keys = self.conn.query_raw(FOREIGN_KEYS, &[]).await?;
        let checks = self.conn.query_raw(CHECKS, &[]).await?;
        let generators = self.conn.query_raw(GENERATORS, &[]).await?;
        let triggers = self.conn.query_raw(TRIGGERS, &[]).await?;
        build_schema(relations, columns, indexes, foreign_keys, checks, generators, triggers)
    }
}

#[async_trait::async_trait]
impl SqlSchemaDescriberBackend for SqlSchemaDescriber<'_> {
    async fn describe(&self, schemas: &[&str]) -> DescriberResult<SqlSchema> {
        if schemas.iter().any(|schema| !schema.is_empty()) {
            return Err(unsupported("database namespaces are not supported"));
        }
        self.describe_impl().await
    }

    async fn version(&self) -> DescriberResult<Option<String>> {
        let result = self
            .conn
            .query_raw(
                "SELECT RDB$GET_CONTEXT('SYSTEM', 'ENGINE_VERSION') AS \"version\" FROM RDB$DATABASE",
                &[],
            )
            .await?;
        let row = result.into_single()?;
        Ok(Some(required_string(&row, "version")?))
    }
}

// Quoted aliases are intentional: the adapter must retain their exact case.
const RELATIONS: &str = r#"
SELECT r.RDB$RELATION_NAME AS "table_name", COALESCE(r.RDB$RELATION_TYPE, 0) AS "relation_type",
       r.RDB$DESCRIPTION AS "description"
FROM RDB$RELATIONS r
WHERE COALESCE(r.RDB$SYSTEM_FLAG, 0) = 0
ORDER BY r.RDB$RELATION_NAME
"#;

const COLUMNS: &str = r#"
SELECT rf.RDB$RELATION_NAME AS "table_name", rf.RDB$FIELD_NAME AS "column_name",
       f.RDB$FIELD_TYPE AS "field_type", f.RDB$FIELD_SUB_TYPE AS "field_sub_type",
       f.RDB$FIELD_PRECISION AS "field_precision", f.RDB$FIELD_SCALE AS "field_scale",
       f.RDB$CHARACTER_LENGTH AS "character_length", cs.RDB$CHARACTER_SET_NAME AS "character_set",
       COALESCE(rf.RDB$COLLATION_ID, f.RDB$COLLATION_ID, 0) AS "collation_id",
       COALESCE(rf.RDB$NULL_FLAG, f.RDB$NULL_FLAG, 0) AS "not_null",
       COALESCE(f.RDB$NULL_FLAG, 0) AS "domain_not_null",
       rf.RDB$DEFAULT_SOURCE AS "column_default", f.RDB$DEFAULT_SOURCE AS "domain_default",
       rf.RDB$IDENTITY_TYPE AS "identity_type", rf.RDB$GENERATOR_NAME AS "generator_name",
       rf.RDB$FIELD_SOURCE AS "field_source", f.RDB$DIMENSIONS AS "dimensions",
       f.RDB$COMPUTED_SOURCE AS "computed_source", f.RDB$VALIDATION_SOURCE AS "validation_source",
       rf.RDB$DESCRIPTION AS "description",
       CASE WHEN f.RDB$COMPUTED_BLR IS NOT NULL THEN 1 ELSE 0 END AS "is_computed",
       CASE WHEN f.RDB$VALIDATION_BLR IS NOT NULL THEN 1 ELSE 0 END AS "has_validation",
       CASE WHEN rf.RDB$DEFAULT_VALUE IS NOT NULL OR f.RDB$DEFAULT_VALUE IS NOT NULL THEN 1 ELSE 0 END AS "has_default"
FROM RDB$RELATION_FIELDS rf
JOIN RDB$RELATIONS r ON r.RDB$RELATION_NAME = rf.RDB$RELATION_NAME
JOIN RDB$FIELDS f ON f.RDB$FIELD_NAME = rf.RDB$FIELD_SOURCE
LEFT JOIN RDB$CHARACTER_SETS cs ON cs.RDB$CHARACTER_SET_ID = f.RDB$CHARACTER_SET_ID
WHERE COALESCE(r.RDB$SYSTEM_FLAG, 0) = 0
ORDER BY rf.RDB$RELATION_NAME, rf.RDB$FIELD_POSITION
"#;

const INDEXES: &str = r#"
SELECT i.RDB$RELATION_NAME AS "table_name", i.RDB$INDEX_NAME AS "index_name",
       i.RDB$UNIQUE_FLAG AS "is_unique", COALESCE(i.RDB$INDEX_TYPE, 0) AS "is_descending",
       COALESCE(i.RDB$INDEX_INACTIVE, 0) AS "is_inactive", i.RDB$EXPRESSION_SOURCE AS "expression_source",
       i.RDB$FOREIGN_KEY AS "foreign_key_index", s.RDB$FIELD_NAME AS "column_name",
       s.RDB$FIELD_POSITION AS "position", rc.RDB$CONSTRAINT_NAME AS "constraint_name",
       rc.RDB$CONSTRAINT_TYPE AS "constraint_type",
       CASE WHEN i.RDB$EXPRESSION_BLR IS NOT NULL THEN 1 ELSE 0 END AS "is_expression"
FROM RDB$INDICES i
JOIN RDB$RELATIONS r ON r.RDB$RELATION_NAME = i.RDB$RELATION_NAME
LEFT JOIN RDB$INDEX_SEGMENTS s ON s.RDB$INDEX_NAME = i.RDB$INDEX_NAME
LEFT JOIN RDB$RELATION_CONSTRAINTS rc ON rc.RDB$INDEX_NAME = i.RDB$INDEX_NAME
  AND rc.RDB$CONSTRAINT_TYPE IN ('PRIMARY KEY', 'UNIQUE')
WHERE COALESCE(r.RDB$SYSTEM_FLAG, 0) = 0
ORDER BY i.RDB$RELATION_NAME, i.RDB$INDEX_NAME, s.RDB$FIELD_POSITION
"#;

const FOREIGN_KEYS: &str = r#"
SELECT rc.RDB$RELATION_NAME AS "table_name", rc.RDB$CONSTRAINT_NAME AS "constraint_name",
       rc.RDB$INDEX_NAME AS "index_name", s.RDB$FIELD_NAME AS "column_name", s.RDB$FIELD_POSITION AS "position",
       target.RDB$RELATION_NAME AS "referenced_table", target_s.RDB$FIELD_NAME AS "referenced_column",
       ref.RDB$DELETE_RULE AS "delete_rule", ref.RDB$UPDATE_RULE AS "update_rule"
FROM RDB$RELATION_CONSTRAINTS rc
JOIN RDB$REF_CONSTRAINTS ref ON ref.RDB$CONSTRAINT_NAME = rc.RDB$CONSTRAINT_NAME
JOIN RDB$RELATION_CONSTRAINTS target ON target.RDB$CONSTRAINT_NAME = ref.RDB$CONST_NAME_UQ
JOIN RDB$INDEX_SEGMENTS s ON s.RDB$INDEX_NAME = rc.RDB$INDEX_NAME
JOIN RDB$INDEX_SEGMENTS target_s ON target_s.RDB$INDEX_NAME = target.RDB$INDEX_NAME
  AND target_s.RDB$FIELD_POSITION = s.RDB$FIELD_POSITION
JOIN RDB$RELATIONS r ON r.RDB$RELATION_NAME = rc.RDB$RELATION_NAME
WHERE rc.RDB$CONSTRAINT_TYPE = 'FOREIGN KEY' AND COALESCE(r.RDB$SYSTEM_FLAG, 0) = 0
ORDER BY rc.RDB$RELATION_NAME, rc.RDB$CONSTRAINT_NAME, s.RDB$FIELD_POSITION
"#;

const CHECKS: &str = r#"
SELECT rc.RDB$RELATION_NAME AS "table_name", rc.RDB$CONSTRAINT_NAME AS "constraint_name"
FROM RDB$RELATION_CONSTRAINTS rc
JOIN RDB$RELATIONS r ON r.RDB$RELATION_NAME = rc.RDB$RELATION_NAME
WHERE rc.RDB$CONSTRAINT_TYPE = 'CHECK' AND COALESCE(r.RDB$SYSTEM_FLAG, 0) = 0
ORDER BY rc.RDB$RELATION_NAME, rc.RDB$CONSTRAINT_NAME
"#;

const GENERATORS: &str = r#"
SELECT RDB$GENERATOR_NAME AS "generator_name", COALESCE(RDB$SYSTEM_FLAG, 0) AS "system_flag",
       RDB$INITIAL_VALUE AS "initial_value", RDB$GENERATOR_INCREMENT AS "increment"
FROM RDB$GENERATORS
WHERE COALESCE(RDB$SYSTEM_FLAG, 0) IN (0, 6)
ORDER BY RDB$GENERATOR_NAME
"#;

const TRIGGERS: &str = r#"
SELECT RDB$TRIGGER_NAME AS "trigger_name", RDB$RELATION_NAME AS "table_name",
       RDB$TRIGGER_SOURCE AS "source", COALESCE(RDB$TRIGGER_INACTIVE, 0) AS "inactive"
FROM RDB$TRIGGERS
WHERE COALESCE(RDB$SYSTEM_FLAG, 0) = 0
ORDER BY RDB$TRIGGER_NAME
"#;

fn build_schema(
    relations: ResultSet,
    columns: ResultSet,
    indexes: ResultSet,
    foreign_keys: ResultSet,
    checks: ResultSet,
    generators: ResultSet,
    triggers: ResultSet,
) -> DescriberResult<SqlSchema> {
    let mut schema = SqlSchema::default();
    // Firebird has no database namespaces. Match the calculator's None namespace
    // rather than creating Some(""): the differ treats those as different tables.
    let namespace = NamespaceId::default();
    let mut ext = FirebirdSchemaExt::default();
    let mut table_ids = BTreeMap::new();
    let mut column_ids = BTreeMap::new();

    for row in relations {
        let name = identifier(&row, "table_name")?;
        if name == MIGRATION_LOCK_TABLE {
            continue;
        }
        let relation_type = required_i64(&row, "relation_type")?;
        if relation_type != 0 {
            return Err(unsupported(format!(
                "relation {name:?} has relation type {relation_type}; only persistent tables are supported (views, external and temporary tables are unsupported)"
            )));
        }
        let table_id = schema.push_table(name.clone(), namespace, optional_string(&row, "description")?);
        if table_ids.insert(name.clone(), table_id).is_some() {
            return Err(inconsistent(format!("duplicate table {name:?}")));
        }
    }

    for row in columns {
        let table = identifier(&row, "table_name")?;
        if table == MIGRATION_LOCK_TABLE {
            continue;
        }
        let name = identifier(&row, "column_name")?;
        let table_id = lookup(&table_ids, &table, "table")?;
        if optional_i64(&row, "dimensions")?.unwrap_or(0) != 0 {
            return Err(unsupported(format!("array column {table:?}.{name:?}")));
        }
        if required_i64(&row, "is_computed")? != 0 || optional_string(&row, "computed_source")?.is_some() {
            return Err(unsupported(format!("computed column {table:?}.{name:?}")));
        }
        if required_i64(&row, "has_validation")? != 0 || optional_string(&row, "validation_source")?.is_some() {
            return Err(unsupported(format!("domain CHECK on column {table:?}.{name:?}")));
        }
        let identity_type = optional_i64(&row, "identity_type")?;
        let identity = match identity_type {
            None => None,
            Some(1) => Some(Identity {
                generator_name: identifier(&row, "generator_name")?,
            }),
            Some(other) => return Err(unsupported(format!("identity type {other} on {table:?}.{name:?}"))),
        };
        let not_null = required_i64(&row, "not_null")?;
        if !matches!(not_null, 0 | 1) {
            return Err(inconsistent(format!(
                "invalid null flag {not_null} on {table:?}.{name:?}"
            )));
        }
        let arity = if not_null == 1 || identity.is_some() {
            ColumnArity::Required
        } else {
            ColumnArity::Nullable
        };
        let tpe = column_type(&row, arity)?;
        if identity.is_some() && !matches!(tpe.family, ColumnTypeFamily::Int | ColumnTypeFamily::BigInt) {
            return Err(unsupported(format!(
                "identity on non-integer column {table:?}.{name:?}"
            )));
        }
        let default_source = optional_string(&row, "column_default")?.or(optional_string(&row, "domain_default")?);
        if required_i64(&row, "has_default")? != 0 && default_source.is_none() {
            return Err(unsupported(format!(
                "default without retained SQL source on {table:?}.{name:?}"
            )));
        }
        if identity.is_some() && default_source.is_some() {
            return Err(inconsistent(format!("identity {table:?}.{name:?} also has a DEFAULT")));
        }
        let default = default_source
            .as_deref()
            .map(|source| parse_default(source, &tpe.family))
            .transpose()?;
        let column_id = schema.push_table_column(
            table_id,
            Column {
                name: name.clone(),
                tpe,
                auto_increment: identity.is_some(),
                description: optional_string(&row, "description")?,
            },
        );
        if column_ids.insert((table, name), column_id).is_some() {
            return Err(inconsistent("duplicate column"));
        }
        if let Some(default) = default {
            schema.push_table_default_value(column_id, default);
        }
        if let Some(identity) = identity {
            ext.identities.push((column_id, identity));
        }
        ext.columns.push((
            column_id,
            ColumnMetadata {
                field_source: identifier(&row, "field_source")?,
                character_set: optional_identifier(&row, "character_set")?,
                collation_id: required_i64(&row, "collation_id")?,
                domain_not_null: required_i64(&row, "domain_not_null")? == 1,
                domain_default: optional_string(&row, "domain_default")?,
                column_default: optional_string(&row, "column_default")?,
            },
        ));
    }

    let mut index_ids = BTreeMap::new();
    for row in indexes {
        if optional_string(&row, "foreign_key_index")?.is_some() {
            continue; // The FK backing index is represented by the foreign key, not an extra @@index.
        }
        let table = identifier(&row, "table_name")?;
        if table == MIGRATION_LOCK_TABLE {
            continue;
        }
        let name = identifier(&row, "index_name")?;
        if required_i64(&row, "is_inactive")? != 0
            || required_i64(&row, "is_expression")? != 0
            || optional_string(&row, "expression_source")?.is_some()
        {
            return Err(unsupported(format!(
                "inactive or expression index {name:?} on {table:?}"
            )));
        }
        let table_id = lookup(&table_ids, &table, "index table")?;
        let constraint_name = optional_identifier(&row, "constraint_name")?;
        let key = (table.clone(), name.clone());
        let position = required_i64(&row, "position")?;
        let (index_id, next_position) = match index_ids.entry(key) {
            Entry::Occupied(entry) => entry.into_mut(),
            Entry::Vacant(entry) => {
                let logical_name = constraint_name.clone().unwrap_or_else(|| name.clone());
                let index_id = match optional_identifier(&row, "constraint_type")?.as_deref() {
                    Some("PRIMARY KEY") => schema.push_primary_key(table_id, logical_name),
                    Some("UNIQUE") => schema.push_unique_constraint(table_id, logical_name),
                    None if optional_i64(&row, "is_unique")?.unwrap_or(0) == 1 => {
                        schema.push_unique_constraint(table_id, logical_name)
                    }
                    None => schema.push_index(table_id, logical_name),
                    Some(other) => return Err(inconsistent(format!("unexpected index constraint {other:?}"))),
                };
                ext.indexes.push((
                    index_id,
                    IndexMetadata {
                        database_name: name,
                        constraint_name,
                    },
                ));
                entry.insert((index_id, 0))
            }
        };
        if position != *next_position {
            return Err(inconsistent("non-contiguous index segment positions"));
        }
        *next_position += 1;
        let column = identifier(&row, "column_name")?;
        let column_id = lookup(&column_ids, &(table, column), "index column")?;
        let sort_order = match required_i64(&row, "is_descending")? {
            0 => SQLSortOrder::Asc,
            1 => SQLSortOrder::Desc,
            other => return Err(inconsistent(format!("unexpected index direction {other}"))),
        };
        schema.push_index_column(IndexColumn {
            index_id: *index_id,
            column_id,
            sort_order: Some(sort_order),
            length: None,
        });
    }

    let mut foreign_key_ids = BTreeMap::new();
    for row in foreign_keys {
        let table = identifier(&row, "table_name")?;
        if table == MIGRATION_LOCK_TABLE {
            continue;
        }
        let name = identifier(&row, "constraint_name")?;
        let target = identifier(&row, "referenced_table")?;
        let key = (table.clone(), name.clone());
        let (foreign_key_id, next_position) = match foreign_key_ids.entry(key) {
            Entry::Occupied(entry) => entry.into_mut(),
            Entry::Vacant(entry) => {
                let foreign_key_id = schema.push_foreign_key(
                    Some(name),
                    [
                        lookup(&table_ids, &table, "foreign key table")?,
                        lookup(&table_ids, &target, "referenced table")?,
                    ],
                    [
                        foreign_key_action(&required_string(&row, "delete_rule")?)?,
                        foreign_key_action(&required_string(&row, "update_rule")?)?,
                    ],
                );
                ext.foreign_key_indexes
                    .push((foreign_key_id, identifier(&row, "index_name")?));
                entry.insert((foreign_key_id, 0))
            }
        };
        if required_i64(&row, "position")? != *next_position {
            return Err(inconsistent("non-contiguous foreign key segment positions"));
        }
        *next_position += 1;
        let column = identifier(&row, "column_name")?;
        let referenced_column = identifier(&row, "referenced_column")?;
        schema.push_foreign_key_column(
            *foreign_key_id,
            [
                lookup(&column_ids, &(table, column), "foreign key column")?,
                lookup(&column_ids, &(target, referenced_column), "referenced column")?,
            ],
        );
    }

    for row in checks {
        let table = identifier(&row, "table_name")?;
        if table == MIGRATION_LOCK_TABLE {
            continue;
        }
        schema.check_constraints.push((
            lookup(&table_ids, &table, "check table")?,
            identifier(&row, "constraint_name")?,
        ));
    }
    for row in generators {
        ext.generators.push(Generator {
            name: identifier(&row, "generator_name")?,
            system_flag: required_i64(&row, "system_flag")?,
            initial_value: required_i64(&row, "initial_value")?,
            increment: required_i64(&row, "increment")?,
        });
    }
    for row in triggers {
        ext.triggers.push(Trigger {
            name: identifier(&row, "trigger_name")?,
            relation_name: optional_identifier(&row, "table_name")?,
            source: optional_string(&row, "source")?,
            inactive: required_i64(&row, "inactive")? != 0,
        });
    }
    for (_, identity) in &ext.identities {
        if !ext
            .generators
            .iter()
            .any(|generator| generator.name == identity.generator_name && generator.system_flag == 6)
        {
            return Err(inconsistent(format!(
                "identity generator {:?} was not found with system flag 6",
                identity.generator_name
            )));
        }
    }
    schema.set_connector_data(Box::new(ext));
    Ok(schema)
}

fn column_type(row: &ResultRow, arity: ColumnArity) -> DescriberResult<ColumnType> {
    use ColumnTypeFamily as Family;
    let code = required_i64(row, "field_type")?;
    let subtype = optional_i64(row, "field_sub_type")?.unwrap_or(0);
    let (family, native, full_data_type) = if matches!(code, 7 | 8 | 16) && matches!(subtype, 1 | 2) {
        let precision = required_i64(row, "field_precision")?;
        let scale = required_i64(row, "field_scale")?
            .checked_neg()
            .ok_or_else(|| inconsistent("numeric scale overflow"))?;
        if !(1..=18).contains(&precision) || !(0..=precision).contains(&scale) {
            return Err(unsupported(format!("numeric precision/scale ({precision},{scale})")));
        }
        let args = Some((precision as u32, scale as u32));
        if subtype == 1 {
            (
                Family::Decimal,
                FirebirdType::Numeric(args),
                format!("NUMERIC({precision},{scale})"),
            )
        } else {
            (
                Family::Decimal,
                FirebirdType::Decimal(args),
                format!("DECIMAL({precision},{scale})"),
            )
        }
    } else {
        match (code, subtype) {
            (7, 0) => (Family::Int, FirebirdType::SmallInt, "SMALLINT".into()),
            (8, 0) => (Family::Int, FirebirdType::Integer, "INTEGER".into()),
            (16, 0) => (Family::BigInt, FirebirdType::BigInt, "BIGINT".into()),
            (10, 0) => (Family::Float, FirebirdType::Float, "FLOAT".into()),
            (27, 0) => (Family::Float, FirebirdType::DoublePrecision, "DOUBLE PRECISION".into()),
            (23, 0) => (Family::Boolean, FirebirdType::Boolean, "BOOLEAN".into()),
            (12, 0) => (Family::DateTime, FirebirdType::Date, "DATE".into()),
            (13, 0) => (Family::DateTime, FirebirdType::Time, "TIME".into()),
            (35, 0) => (Family::DateTime, FirebirdType::Timestamp, "TIMESTAMP".into()),
            (14 | 37, 0) => {
                let length = required_i64(row, "character_length")?;
                if !(1..=8191).contains(&length) {
                    return Err(unsupported(format!(
                        "character length {length} outside supported UTF8 range 1..8191"
                    )));
                }
                require_utf8(row)?;
                if code == 14 {
                    (
                        Family::String,
                        FirebirdType::Char(length as u32),
                        format!("CHAR({length})"),
                    )
                } else {
                    (
                        Family::String,
                        FirebirdType::VarChar(length as u32),
                        format!("VARCHAR({length})"),
                    )
                }
            }
            (261, 0) => (Family::Binary, FirebirdType::Blob, "BLOB SUB_TYPE BINARY".into()),
            (261, 1) => {
                require_utf8(row)?;
                (Family::String, FirebirdType::Text, "BLOB SUB_TYPE TEXT".into())
            }
            _ => return Err(unsupported(format!("column type code {code}, subtype {subtype}"))),
        }
    };
    Ok(ColumnType {
        full_data_type,
        family,
        arity,
        native_type: Some(NativeTypeInstance::new(native)),
    })
}

fn require_utf8(row: &ResultRow) -> DescriberResult<()> {
    let charset = identifier(row, "character_set")?;
    if charset != "UTF8" {
        return Err(unsupported(format!(
            "character set {charset:?}; this connector currently requires UTF8 text columns"
        )));
    }
    if required_i64(row, "collation_id")? != 0 {
        return Err(unsupported("non-default text collation"));
    }
    Ok(())
}

/// Whether a default is in the supported Firebird 3 literal/context-variable subset.
///
/// Firebird 3 does not permit general expressions as column defaults. In particular,
/// sequences and arbitrary functions must not be emitted as DEFAULT expressions.
/// This is shared with migration preflight so introspection and DDL agree.
pub fn is_supported_default_expression(expression: &str) -> bool {
    static NUMBER: LazyLock<Regex> =
        LazyLock::new(|| Regex::new(r"^[+-]?(?:[0-9]+(?:\.[0-9]*)?|\.[0-9]+)(?:[eE][+-]?[0-9]+)?$").unwrap());
    static HEX_NUMBER: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"^[+-]?0[xX][0-9a-fA-F]{1,16}$").unwrap());
    static CONTEXT: LazyLock<Regex> = LazyLock::new(|| {
        Regex::new(r"(?i)^(?:USER|CURRENT_(?:USER|ROLE|CONNECTION|TRANSACTION|DATE)|(?:CURRENT_TIME|CURRENT_TIMESTAMP|LOCALTIME|LOCALTIMESTAMP)(?:\s*\(\s*[0-3]\s*\))?)$").unwrap()
    });
    let expression = expression.trim();
    if ["NULL", "TRUE", "FALSE", "UNKNOWN"]
        .iter()
        .any(|value| expression.eq_ignore_ascii_case(value))
        || NUMBER.is_match(expression)
        || HEX_NUMBER.is_match(expression)
        || CONTEXT.is_match(expression)
        || is_string_literal(expression)
    {
        return true;
    }
    if let Some((prefix, literal)) = expression.split_once(char::is_whitespace)
        && ["DATE", "TIME", "TIMESTAMP"]
            .iter()
            .any(|value| prefix.eq_ignore_ascii_case(value))
    {
        return unquote_literal(literal.trim_start()).is_some();
    }
    // A character-set introducer can precede a regular, q-quoted or hex string.
    if let Some(introduced) = expression.strip_prefix('_') {
        let end = introduced.find(|character: char| character.is_whitespace() || character == '\'');
        if let Some(end) = end {
            let (charset, literal) = introduced.split_at(end);
            if charset.len() <= 31
                && charset.starts_with(|character: char| character.is_ascii_alphabetic())
                && charset
                    .chars()
                    .all(|character| character.is_ascii_alphanumeric() || matches!(character, '_' | '$'))
            {
                return is_string_literal(literal.trim_start());
            }
        }
    }
    false
}

fn is_string_literal(expression: &str) -> bool {
    if unquote_literal(expression).is_some() {
        return true;
    }
    expression
        .strip_prefix("x'")
        .or_else(|| expression.strip_prefix("X'"))
        .and_then(|literal| literal.strip_suffix('\''))
        .is_some_and(|hex| hex.len() % 2 == 0 && hex.bytes().all(|byte| byte.is_ascii_hexdigit()))
}

fn parse_default(source: &str, family: &ColumnTypeFamily) -> DescriberResult<DefaultValue> {
    let source = source.trim();
    let expression = match source.get(..7) {
        Some(prefix) if prefix.eq_ignore_ascii_case("DEFAULT") && source[7..].starts_with(char::is_whitespace) => {
            source[7..].trim()
        }
        _ => {
            return Err(inconsistent(format!(
                "default source does not start with DEFAULT: {source:?}"
            )));
        }
    };
    if expression.is_empty() {
        return Err(inconsistent("empty DEFAULT expression"));
    }
    if !is_supported_default_expression(expression) {
        return Err(unsupported(format!(
            "default expression {expression:?}; Firebird 3 defaults require a literal, context variable or NULL"
        )));
    }
    if expression.eq_ignore_ascii_case("NULL") {
        // PSL has no scalar @default(null). Keep an explicit database NULL
        // distinguishable from an absent default without emitting invalid PSL.
        return Ok(DefaultValue::db_generated(expression));
    }
    let value = match family {
        ColumnTypeFamily::Int => expression.parse::<i64>().ok().map(PrismaValue::Int),
        ColumnTypeFamily::BigInt => expression.parse::<i64>().ok().map(PrismaValue::BigInt),
        ColumnTypeFamily::Float | ColumnTypeFamily::Decimal => bigdecimal::BigDecimal::from_str(expression)
            .ok()
            .map(PrismaValue::Float),
        ColumnTypeFamily::Boolean if expression.eq_ignore_ascii_case("TRUE") => Some(PrismaValue::Boolean(true)),
        ColumnTypeFamily::Boolean if expression.eq_ignore_ascii_case("FALSE") => Some(PrismaValue::Boolean(false)),
        ColumnTypeFamily::String => unquote_literal(expression).map(PrismaValue::String),
        ColumnTypeFamily::DateTime if expression.eq_ignore_ascii_case("CURRENT_TIMESTAMP") => {
            return Ok(DefaultValue::now());
        }
        _ => None,
    };
    Ok(value
        .map(DefaultValue::value)
        .unwrap_or_else(|| DefaultValue::db_generated(expression)))
}

// Parse a single standard or q-quoted SQL string literal, rejecting expressions.
fn unquote_literal(expression: &str) -> Option<String> {
    if let Some(inner) = expression
        .strip_prefix('\'')
        .and_then(|literal| literal.strip_suffix('\''))
    {
        let mut result = String::new();
        let mut chars = inner.chars();
        while let Some(character) = chars.next() {
            if character == '\'' && chars.next()? != '\'' {
                return None;
            }
            result.push(character);
        }
        return Some(result);
    }
    let mut chars = expression
        .strip_prefix("q'")
        .or_else(|| expression.strip_prefix("Q'"))?
        .chars();
    let closing = match chars.next()? {
        '(' => ')',
        '{' => '}',
        '[' => ']',
        '<' => '>',
        '\'' => return None,
        character => character,
    };
    let terminator = format!("{closing}'");
    let inner = chars.as_str().strip_suffix(&terminator)?;
    (!inner.contains(&terminator)).then(|| inner.to_owned())
}

fn foreign_key_action(action: &str) -> DescriberResult<ForeignKeyAction> {
    match action.trim_end_matches(' ') {
        "NO ACTION" => Ok(ForeignKeyAction::NoAction),
        "CASCADE" => Ok(ForeignKeyAction::Cascade),
        "SET NULL" => Ok(ForeignKeyAction::SetNull),
        "SET DEFAULT" => Ok(ForeignKeyAction::SetDefault),
        other => Err(unsupported(format!("foreign key action {other:?}"))),
    }
}

fn lookup<K: Ord + fmt::Debug, V: Copy>(map: &BTreeMap<K, V>, key: &K, kind: &str) -> DescriberResult<V> {
    map.get(key)
        .copied()
        .ok_or_else(|| inconsistent(format!("missing {kind} {key:?}")))
}

fn identifier(row: &ResultRow, name: &str) -> DescriberResult<String> {
    checked_identifier(required_string(row, name)?)
}

fn optional_identifier(row: &ResultRow, name: &str) -> DescriberResult<Option<String>> {
    optional_string(row, name)?.map(checked_identifier).transpose()
}

fn checked_identifier(value: String) -> DescriberResult<String> {
    let value = value.trim_end_matches(' ');
    if value.is_empty() {
        return Err(inconsistent("empty identifier"));
    }
    if value.len() > 31 || value.chars().any(|character| character > '\u{ffff}') {
        return Err(unsupported(format!(
            "identifier {value:?}; this connector accepts at most 31 UTF8 bytes and only Unicode BMP characters"
        )));
    }
    Ok(value.to_owned())
}

fn required_string(row: &ResultRow, name: &str) -> DescriberResult<String> {
    optional_string(row, name)?.ok_or_else(|| inconsistent(format!("missing catalog string {name:?}")))
}

fn optional_string(row: &ResultRow, name: &str) -> DescriberResult<Option<String>> {
    let value = row
        .get(name)
        .ok_or_else(|| inconsistent(format!("missing catalog field {name:?}")))?;
    if value.is_null() {
        return Ok(None);
    }
    row.get_string(name)
        .map(Some)
        .ok_or_else(|| inconsistent(format!("catalog field {name:?} is not text")))
}

fn required_i64(row: &ResultRow, name: &str) -> DescriberResult<i64> {
    optional_i64(row, name)?.ok_or_else(|| inconsistent(format!("missing catalog integer {name:?}")))
}

fn optional_i64(row: &ResultRow, name: &str) -> DescriberResult<Option<i64>> {
    let value = row
        .get(name)
        .ok_or_else(|| inconsistent(format!("missing catalog field {name:?}")))?;
    if value.is_null() {
        return Ok(None);
    }
    row.get_i64(name)
        .map(Some)
        .ok_or_else(|| inconsistent(format!("catalog field {name:?} is not an integer")))
}

fn unsupported(message: impl fmt::Display) -> DescriberError {
    Error::builder(ErrorKind::ConversionError(
        format!("Firebird 3 introspection does not support {message}.").into(),
    ))
    .build()
    .into()
}

fn inconsistent(message: impl fmt::Display) -> DescriberError {
    Error::builder(ErrorKind::ConversionError(
        format!("Firebird catalog is inconsistent: {message}.").into(),
    ))
    .build()
    .into()
}

