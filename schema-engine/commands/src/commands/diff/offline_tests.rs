// Added for experimental Firebird support (2026-10-18); see MODIFICATIONS.md.
use super::*;
use json_rpc::types::{SchemaContainer, SchemasContainer};
use psl::parser_database::NoExtensionTypes;

const SCHEMA: &str = r#"
datasource db {
  provider = "firebird"
}
model OfflineItem {
  id Int @id @default(autoincrement())
  name String @db.VarChar(50)
}
"#;

fn datamodel(schema: &str) -> DiffTarget {
    DiffTarget::SchemaDatamodel(SchemasContainer {
        files: vec![SchemaContainer {
            path: "schema.prisma".to_owned(),
            content: schema.to_owned(),
        }],
    })
}

fn params(from: DiffTarget, to: DiffTarget) -> DiffParams {
    DiffParams {
        from,
        to,
        script: true,
        exit_code: Some(true),
        filters: Default::default(),
    }
}

#[test]
fn diff_datamodels_renders_real_firebird_identity_ddl_and_exit_two_without_url() {
    let result = diff_datamodels(params(DiffTarget::Empty, datamodel(SCHEMA)), &NoExtensionTypes).unwrap();
    let sql = result.stdout.unwrap();
    assert_eq!(result.exit_code, 2);
    assert!(sql.contains("CREATE TABLE \"OfflineItem\""), "{sql}");
    assert!(sql.contains("GENERATED BY DEFAULT AS IDENTITY"), "{sql}");
    assert!(sql.contains("VARCHAR(50) CHARACTER SET UTF8"), "{sql}");
    assert!(sql.ends_with('\n'));
}

#[test]
fn diff_datamodels_identical_schema_returns_empty_script_and_exit_zero() {
    let result = diff_datamodels(params(datamodel(SCHEMA), datamodel(SCHEMA)), &NoExtensionTypes).unwrap();
    assert_eq!(result.exit_code, 0);
    assert_eq!(result.stdout.as_deref(), Some("-- This is an empty migration.\n"));
}

#[test]
fn diff_datamodels_changed_schema_can_disable_exit_code_and_render_summary() {
    let mut input = params(DiffTarget::Empty, datamodel(SCHEMA));
    input.exit_code = Some(false);
    input.script = false;
    let result = diff_datamodels(input, &NoExtensionTypes).unwrap();
    let summary = result.stdout.unwrap();
    assert_eq!(result.exit_code, 0);
    assert!(summary.contains("OfflineItem"), "{summary}");
    assert!(!summary.contains("CREATE TABLE"), "{summary}");
    assert!(summary.ends_with('\n'));
}

#[test]
fn diff_datamodels_supports_schema_to_empty_and_schema_to_schema() {
    let result = diff_datamodels(params(datamodel(SCHEMA), DiffTarget::Empty), &NoExtensionTypes).unwrap();
    assert_eq!(result.exit_code, 2);
    assert!(result.stdout.unwrap().contains("DROP TABLE \"OfflineItem\""));

    let changed = SCHEMA.replace("  name String", "  note String?\n  name String");
    let result = diff_datamodels(params(datamodel(SCHEMA), datamodel(&changed)), &NoExtensionTypes).unwrap();
    let sql = result.stdout.unwrap();
    assert_eq!(result.exit_code, 2);
    assert!(sql.contains("ALTER TABLE \"OfflineItem\" ADD \"note\""), "{sql}");
}

#[test]
fn diff_datamodels_accepts_real_multifile_datamodels() {
    let files = SchemasContainer {
        files: vec![
            SchemaContainer {
                path: "datasource.prisma".into(),
                content: "datasource db {\n provider = \"firebird\"\n}".into(),
            },
            SchemaContainer {
                path: "model.prisma".into(),
                content: "model SplitItem {\n id Int @id\n}".into(),
            },
        ],
    };
    let result = diff_datamodels(
        params(DiffTarget::Empty, DiffTarget::SchemaDatamodel(files)),
        &NoExtensionTypes,
    )
    .unwrap();
    assert!(result.stdout.unwrap().contains("CREATE TABLE \"SplitItem\""));
}

#[test]
fn diff_datamodels_rejects_different_providers_before_diffing() {
    let sqlite = SCHEMA.replace("\"firebird\"", "\"sqlite\"");
    let error = diff_datamodels(params(datamodel(SCHEMA), datamodel(&sqlite)), &NoExtensionTypes).unwrap_err();
    assert!(error.to_string().contains("same provider"), "{error}");
}

#[test]
fn diff_datamodels_rejects_all_live_targets_on_either_side() {
    for target in [
        serde_json::json!({ "tag": "url", "url": "firebird://unreachable.invalid/test" }),
        serde_json::json!({ "tag": "schemaDatasource", "files": [], "configDir": "." }),
        serde_json::json!({
            "tag": "migrations", "baseDir": ".", "shadowDbInitScript": "",
            "lockfile": { "path": "migration_lock.toml", "content": "provider = \"firebird\"" },
            "migrationDirectories": []
        }),
    ] {
        for live_from in [false, true] {
            let target = serde_json::from_value(target.clone()).unwrap();
            let input = if live_from {
                params(target, datamodel("invalid PSL must not be parsed"))
            } else {
                params(datamodel("invalid PSL must not be parsed"), target)
            };
            let error = diff_datamodels(input, &NoExtensionTypes).unwrap_err();
            assert!(
                error.to_string().contains("only supports Empty and SchemaDatamodel"),
                "{error}"
            );
        }
    }
}

#[test]
fn diff_datamodels_rejects_empty_empty_missing_datasource_and_invalid_psl() {
    let error = diff_datamodels(params(DiffTarget::Empty, DiffTarget::Empty), &NoExtensionTypes).unwrap_err();
    assert!(error.to_string().contains("at least one SchemaDatamodel"));
    for schema in ["model MissingSource {\n id Int @id\n}", "not valid PSL"] {
        assert!(diff_datamodels(params(DiffTarget::Empty, datamodel(schema)), &NoExtensionTypes).is_err());
    }
}

#[test]
fn diff_datamodels_runs_full_psl_capability_validation() {
    for field in ["  body Json?", "  body String[]"] {
        let schema = SCHEMA.replace("  name String", &format!("{field}\n  name String"));
        assert!(diff_datamodels(params(DiffTarget::Empty, datamodel(&schema)), &NoExtensionTypes).is_err());
    }
}

#[test]
fn diff_datamodels_rejects_unsafe_defaults_and_identity_changes_before_sql_output() {
    let unsafe_default = SCHEMA.replace(
        "  name String",
        "  serial Int @default(dbgenerated(\"NEXT VALUE FOR counter\"))\n  name String",
    );
    let error = diff_datamodels(params(DiffTarget::Empty, datamodel(&unsafe_default)), &NoExtensionTypes).unwrap_err();
    assert!(error.to_string().to_ascii_lowercase().contains("default"), "{error}");

    let manual_id = SCHEMA.replace(" @default(autoincrement())", "");
    let error = diff_datamodels(params(datamodel(&manual_id), datamodel(SCHEMA)), &NoExtensionTypes).unwrap_err();
    assert!(error.to_string().contains("identity"), "{error}");
}

#[test]
fn diff_datamodels_honors_filters_and_validates_namespaces() {
    let mut input = params(DiffTarget::Empty, datamodel(SCHEMA));
    input.filters.external_tables.push("OfflineItem".into());
    let result = diff_datamodels(input, &NoExtensionTypes).unwrap();
    assert_eq!(result.exit_code, 0);
    assert_eq!(result.stdout.as_deref(), Some("-- This is an empty migration.\n"));

    let mut input = params(DiffTarget::Empty, datamodel(SCHEMA));
    input.filters.external_tables.push("public.OfflineItem".into());
    assert!(diff_datamodels(input, &NoExtensionTypes).is_err());
}

#[cfg(all(feature = "sqlite", feature = "postgresql"))]
#[test]
fn diff_datamodels_preserves_other_enabled_dialects() {
    for provider in ["sqlite", "postgresql"] {
        let schema = format!("datasource db {{\n provider = \"{provider}\"\n}}\nmodel PlainItem {{\n id Int @id\n}}");
        let result = diff_datamodels(params(DiffTarget::Empty, datamodel(&schema)), &NoExtensionTypes).unwrap();
        assert_eq!(result.exit_code, 2);
        assert!(result.stdout.unwrap().contains("CREATE TABLE \"PlainItem\""));
    }
}
