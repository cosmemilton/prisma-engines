/*! Added for experimental Firebird support (2026-10-18); see MODIFICATIONS.md. */
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { Socket } from 'node:net'
import { dirname, resolve } from 'node:path'
import { after, afterEach, test } from 'node:test'
import { fileURLToPath, pathToFileURL } from 'node:url'

const outputDirectory = process.env.PRISMA_SCHEMA_ENGINE_WASM_DIR ||
  resolve(dirname(fileURLToPath(import.meta.url)), '../../../target/schema-engine-wasm')
const glue = await import(pathToFileURL(resolve(outputDirectory, 'schema_engine_bg.js')).href)
const module = await WebAssembly.compile(await readFile(resolve(outputDirectory, 'schema_engine_bg.wasm')))
const instance = await WebAssembly.instantiate(module, { './schema_engine_bg.js': glue })
glue.__wbg_set_wasm(instance.exports)
instance.exports.__wbindgen_start()

let connectionAttempts = 0
const originalConnect = Socket.prototype.connect
Socket.prototype.connect = function () {
  connectionAttempts++
  throw new Error('Offline diff must not open a connection')
}
after(() => { Socket.prototype.connect = originalConnect })
afterEach(() => assert.equal(connectionAttempts, 0))
globalThis.PRISMA_WASM_PANIC_REGISTRY = { set_message: (message) => { throw new Error(message) } }

const schema = `datasource db {
  provider = "firebird"
}
model OfflineItem {
  id Int @id @default(autoincrement())
  name String @db.VarChar(50)
}
`
const empty = { tag: 'empty' }
const datamodel = (content = schema) => ({ tag: 'schemaDatamodel', files: [{ path: 'schema.prisma', content }] })
const input = (from = empty, to = datamodel(), overrides = {}) => ({
  from, to, script: true, exitCode: true,
  filters: { externalTables: [], externalEnums: [] }, ...overrides,
})
const rejects = (params, message) => assert.rejects(() => glue.diffDatamodels(params), (error) => {
  assert.match(String(error), message)
  return true
})

test('module export renders real Firebird DDL without a URL, adapter, or engine instance', async () => {
  assert.equal(typeof glue.diffDatamodels, 'function')
  const pending = glue.diffDatamodels(input())
  assert.ok(pending instanceof Promise)
  const result = await pending
  assert.equal(result.exitCode, 2)
  assert.match(result.stdout, /CREATE TABLE "OfflineItem"/)
  assert.match(result.stdout, /GENERATED BY DEFAULT AS IDENTITY/)
  assert.match(result.stdout, /VARCHAR\(50\) CHARACTER SET UTF8/)
  assert.ok(result.stdout.endsWith('\n'))
})

test('identical datamodels produce a genuine no-op with exit zero', async () => {
  const result = await glue.diffDatamodels(input(datamodel(), datamodel()))
  assert.equal(result.exitCode, 0)
  assert.equal(result.stdout, '-- This is an empty migration.\n')
})

test('exit-code disabled and human-readable summary preserve the existing result contract', async () => {
  const result = await glue.diffDatamodels(input(empty, datamodel(), { script: false, exitCode: false }))
  assert.equal(result.exitCode, 0)
  assert.match(result.stdout, /OfflineItem/)
  assert.doesNotMatch(result.stdout, /CREATE TABLE/)
  assert.ok(result.stdout.endsWith('\n'))
})

test('schema-to-empty and schema-to-schema use the actual Firebird differ', async () => {
  const dropped = await glue.diffDatamodels(input(datamodel(), empty))
  assert.equal(dropped.exitCode, 2)
  assert.match(dropped.stdout, /DROP TABLE "OfflineItem"/)
  const changed = schema.replace('  name String', '  note String?\n  name String')
  const added = await glue.diffDatamodels(input(datamodel(), datamodel(changed)))
  assert.equal(added.exitCode, 2)
  assert.match(added.stdout, /ALTER TABLE "OfflineItem" ADD "note"/)
})

test('multifile schemas and schema filters use the shared validation/calculator', async () => {
  const split = { tag: 'schemaDatamodel', files: [
    { path: 'source.prisma', content: 'datasource db {\n provider = "firebird"\n}' },
    { path: 'model.prisma', content: 'model SplitItem {\n id Int @id\n}' },
  ] }
  assert.match((await glue.diffDatamodels(input(empty, split))).stdout, /CREATE TABLE "SplitItem"/)
  const excluded = await glue.diffDatamodels(input(empty, datamodel(), {
    filters: { externalTables: ['OfflineItem'], externalEnums: [] },
  }))
  assert.equal(excluded.exitCode, 0)
  await assert.rejects(() => glue.diffDatamodels(input(empty, datamodel(), {
    filters: { externalTables: ['public.OfflineItem'], externalEnums: [] },
  })))
})

test('mismatched providers and missing schema/datasource fail explicitly', async () => {
  await rejects(input(datamodel(), datamodel(schema.replace('"firebird"', '"sqlite"'))), /same provider/)
  await rejects(input(empty, empty), /at least one SchemaDatamodel/)
  await rejects(input(empty, datamodel('model Missing {\n id Int @id\n}')), /no datasource/i)
})

test('every live or migration target fails before an invalid schema is parsed', async () => {
  const targets = [
    { tag: 'url', url: 'firebird://unreachable.invalid/test' },
    { tag: 'schemaDatasource', files: [], configDir: '.' },
    { tag: 'migrations', baseDir: '.', shadowDbInitScript: '',
      lockfile: { path: 'migration_lock.toml', content: 'provider = "firebird"' }, migrationDirectories: [] },
  ]
  for (const live of targets) {
    await rejects(input(live, datamodel('invalid PSL')), /only supports Empty and SchemaDatamodel/)
    await rejects(input(datamodel('invalid PSL'), live), /only supports Empty and SchemaDatamodel/)
  }
})

test('unsupported PSL features and unsafe DDL are rejected through real validation/preflight', async () => {
  for (const field of ['  body Json?', '  body String[]']) {
    await assert.rejects(() => glue.diffDatamodels(input(empty, datamodel(schema.replace('  name String', `${field}\n  name String`)))))
  }
  const unsafe = schema.replace('  name String', '  serial Int @default(dbgenerated("NEXT VALUE FOR counter"))\n  name String')
  await rejects(input(empty, datamodel(unsafe)), /default/i)
  await rejects(input(datamodel(schema.replace(' @default(autoincrement())', '')), datamodel()), /identity/i)
})

test('enabled SQLite and PostgreSQL dialects retain their own offline SQL', async () => {
  for (const provider of ['sqlite', 'postgresql']) {
    const plain = `datasource db {\n provider = "${provider}"\n}\nmodel PlainItem {\n id Int @id\n}`
    const result = await glue.diffDatamodels(input(empty, datamodel(plain)))
    assert.equal(result.exitCode, 2)
    assert.match(result.stdout, /CREATE TABLE "PlainItem"/)
  }
})
